// Live integration regression: execute the real UI handlers against the local API.
// Requires the saved recording database and a running server.
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const base=process.env.ADVISOR_URL||'http://127.0.0.1:8765';
const elements=new Map(),requests=[];
const document={querySelector(sel){if(!elements.has(sel))elements.set(sel,{value:'',innerHTML:'',disabled:false});return elements.get(sel)},querySelectorAll(){return []}};
const $=id=>document.querySelector('#'+id);
const fetchProxy=async(path,options)=>{
  const url=path.startsWith('/')?base+path:path;
  if(options?.method==='POST')requests.push({path,body:JSON.parse(options.body)});
  return fetch(url,options);
};
(async()=>{
  const state=await(await fetch(base+'/api/state')).json();
  const code=fs.readFileSync('static/app.js','utf8').replace(/refresh\(\)\.catch\(fail\);\s*$/,'');
  const ctx={document,window:{},fetch:fetchProxy,setTimeout(){},URL,Blob,console};
  vm.createContext(ctx);vm.runInContext(code,ctx);vm.runInContext('state='+JSON.stringify(state),ctx);
  const find=(name,variant)=>{const item=state.inventory.find(x=>x.name===name&&x.variant===variant);assert(item,`${name} ${variant} in recorded inventory`);return item.id};
  $('selectionLeft').value=find('Precision Charge','Aero');
  $('selectionRight').value=find('Distant Strike','Survival');
  $('selectionConditions').value='grounded; no incoming hits';
  $('selectionCritRate').value='';$('selectionWeakRate').value='';
  $('critRate').value='0';$('critRate').disabled=true;
  $('weakRate').value='0';$('weakRate').disabled=true;
  await vm.runInContext('runSelectionCompare()',ctx);
  let request=requests.at(-1);
  assert.equal(request.path,'/api/compare-selections');
  assert.equal(request.body.assumptions.crit_rate,null);
  assert.equal(request.body.assumptions.weakspot_rate,null);
  assert($('selectionResults').innerHTML.includes('Weapon DMG base +2.4%'));
  assert($('selectionResults').innerHTML.includes('additional +1.2% for aerial hit (inactive for stated grounded encounter)'));
  assert($('selectionResults').innerHTML.includes('Crit DMG base +6% (passive'));
  $('selectionCritRate').value='0';
  await vm.runInContext('runSelectionCompare()',ctx);
  request=requests.at(-1);
  assert.equal(request.body.assumptions.crit_rate,0);
  assert($('selectionResults').innerHTML.includes('Crit DMG base +6% (inactive for explicit zero critical-hit share)'));
  $('selectionLeft').value=find('Reload Rampage','Downstar Deviant Energy');
  $('selectionConditions').value='same elevation';$('selectionCritRate').value='';
  await vm.runInContext('runSelectionCompare()',ctx);
  assert($('selectionResults').innerHTML.includes('Elemental DMG base +4.8%'));
  assert($('selectionResults').innerHTML.includes('additional +2.4% for enemy below player, maximum at 5 meters (inactive for stated same-elevation encounter)'));
  $('selectionConditions').value='first monster hit';$('selectionIncomingHit').value='100';
  await vm.runInContext('runCatalogExample()',ctx);
  request=requests.at(-1);
  assert.equal(request.path,'/api/compare-catalog-selections');
  assert.equal(request.body.assumptions.incoming_monster_hit,100);
  assert($('selectionResults').innerHTML.includes('Selected metric unresolved'));
  assert($('selectionResults').innerHTML.includes('Numeric attribute profile incomplete'));
  assert($('selectionResults').innerHTML.includes('ownership not asserted or saved'));
  $('selectionConditions').value='no incoming hits';$('selectionIncomingHit').value='0';
  await vm.runInContext('runCatalogExample()',ctx);
  assert($('selectionResults').innerHTML.includes('Selected metric unresolved'));
  const unresolved=await(await fetch(base+'/api/compare-catalog-selections',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({left:{catalog_id:'mod:weapon_mod:shock-diffusion-survival',level:10},right:{catalog_id:'mod:weapon_mod:shock-rampage-survival',level:12},assumptions:{incoming_monster_hit:100}})})).json();
  assert.equal(unresolved.winner_established,false);
  assert(unresolved.ranking_blockers.some(x=>x.includes('same verified main effect')));
  assert(vm.runInContext('selectionResultsHtml('+JSON.stringify(unresolved)+')',ctx).includes('Selected metric unresolved'));
  $('outCrit').value='0.2';$('outWeak').value='0.2';$('outDuration').value='40';$('outElevation').value='same';
  $('outStamina').checked=false;$('outHpLost').checked=false;$('outProc').checked=false;
  await vm.runInContext('runOutgoingExample()',ctx);
  request=requests.at(-1);
  assert.equal(request.path,'/api/outgoing-example');
  assert.equal(request.body.target.weakspot_share,0.2);
  assert($('outgoingResults').innerHTML.includes('3038.64'));
  assert($('outgoingResults').innerHTML.includes('2983.2'));
  assert($('outgoingResults').innerHTML.includes('30386.4'));
  assert($('outgoingResults').innerHTML.includes('Conditional burst and sustained winner'));
  assert($('outgoingResults').innerHTML.includes('Explicit model assumptions'));
  $('outWeak').value='0';await vm.runInContext('runOutgoingExample()',ctx);
  assert($('outgoingResults').innerHTML.includes('2505.8'));
  $('outStamina').checked=true;await vm.runInContext('runOutgoingExample()',ctx);
  assert($('outgoingResults').innerHTML.includes('No outgoing winner'));
  assert($('outgoingResults').innerHTML.includes('stamina loss'));
  console.log('Live UI → API regression passed: nullable shares, conditional bases, incomplete first-hit profile withholding, outgoing burst/sustained example, and unresolved stamina case');
})().catch(error=>{console.error(error);process.exitCode=1});
